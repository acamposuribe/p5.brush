const uncompand = (x) =>
  x < 0.04045 ? x / 12.92 : Math.pow((x + 0.055) / 1.055, 2.4);

const ks = new Float32Array(SIZE);
const terms = { ks, luminance: 0 };

/**
 * Returns the pigment's K/S per wavelength and its luminance, matching
 * `spectral_linear_to_reflectance`, `KS` and `spectral_reflectance_to_xyz(R).y`.
 * The returned object and its array are reused by the next call.
 * @param {number[]} rgb - sRGB colour in [0, 1].
 * @returns {{ks: Float32Array, luminance: number}}
 */
export function pigmentTerms(rgb) {
  let r = uncompand(rgb[0]), g = uncompand(rgb[1]), b = uncompand(rgb[2]);
  const w = Math.min(r, g, b);
  r -= w; g -= w; b -= w;
  const c = Math.min(g, b);
  const m = Math.min(r, b);
  const y = Math.min(r, g);
  const pr = Math.min(Math.max(0, r - b), Math.max(0, r - g));
  const pg = Math.min(Math.max(0, g - b), Math.max(0, g - r));
  const pb = Math.min(Math.max(0, b - g), Math.max(0, b - r));

  let luminance = 0;
  for (let i = 0, k = 0; i < SIZE; i++, k += 7) {
    const R = Math.max(EPSILON,
      w * BASIS[k] + c * BASIS[k + 1] + m * BASIS[k + 2] + y * BASIS[k + 3] +
      pr * BASIS[k + 4] + pg * BASIS[k + 5] + pb * BASIS[k + 6]);
    luminance += R * CMF_Y[i];
    ks[i] = (1 - R) * (1 - R) / (2 * R);
  }
  terms.luminance = luminance;
  return terms;
}
